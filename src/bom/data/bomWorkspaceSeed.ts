export function buildWorkspaceMainRows(): BomItem[] {
  return WORKSPACE_MAIN_ROWS.map((row, index) => ensureWorkspaceRowDisplayFields({
    ...row,
    id: `ws-main-${index + 1}`,
    rowNumber: index + 1,
  }));
}

/** Ensures Figure Number and SKU are always populated for workspace table display. */
export function ensureWorkspaceRowDisplayFields(row: BomItem): BomItem {
  const figureNumber = row.figureNumber?.trim();
  const sku = row.sku?.trim();
  if (figureNumber && sku) return row;

  const suffix = String(row.rowNumber).padStart(2, '0');
  return {
    ...row,
    figureNumber: figureNumber || row.originalInput || `FP-${suffix}`,
    sku: sku || `${4371000500 + row.rowNumber}`,
  };
}
